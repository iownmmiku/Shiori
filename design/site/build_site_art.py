"""Turn the download page artwork in design/site/ into the files the page uses.

  python design/site/build_site_art.py

Inputs (generated by the owner, white backgrounds except the hero):
  hero.webp, stand.webp, feature-{chat,memory,stickers,local}.webp, chibi-set.webp
Outputs in site/assets/:
  art/hero.webp                      the hero picture, re-encoded
  art/stand.webp, art/feature-*.webp the white page keyed out to transparency
  art/chibi-{happy,annoyed,sleepy}.webp  the three chibis cut apart
  banner.jpg                         README / release / link-preview banner
  icon.png                           favicon (the app icon)

Pillow only. Text on the banner uses Noto Serif SC / Noto Sans SC (SIL OFL).
"""
from __future__ import annotations

from collections import deque
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(__file__).resolve().parent
OUT = ROOT / 'site' / 'assets'
ART = OUT / 'art'
FONTS = Path('C:/Windows/Fonts')


def _flood(w: int, h: int, open_: bytes) -> bytearray:
    """Pixels reachable from the image border through pixels where open_ is non-zero."""
    seen = bytearray(w * h)
    queue = deque(x for x in range(w))
    queue.extend((h - 1) * w + x for x in range(w))
    queue.extend(y * w for y in range(h))
    queue.extend(y * w + w - 1 for y in range(h))
    while queue:
        i = queue.popleft()
        if seen[i] or not open_[i]:
            continue
        seen[i] = 1
        x = i % w
        if x + 1 < w: queue.append(i + 1)
        if x: queue.append(i - 1)
        if i + w < w * h: queue.append(i + w)
        if i >= w: queue.append(i - w)
    return seen


def key_white(image: Image.Image, strand: int = 9) -> Image.Image:
    """Make the white page transparent, keeping antialiased edges and enclosed whites (eyes, shirt).

    Flyaway hair encloses little pockets of the page that a plain flood fill from
    the border cannot reach. The flood therefore runs on a copy where structures
    thinner than ``strand`` pixels are opened away, then only page-white pixels of
    what it reached are cleared, so the strands themselves stay.
    """
    rgb = image.convert('RGB')
    w, h = rgb.size
    raw = rgb.tobytes()
    white = bytes(255 if min(p) >= 228 and max(p) - min(p) <= 18 else 0
                  for p in zip(raw[0::3], raw[1::3], raw[2::3]))
    solid = Image.frombytes('L', (w, h), bytes(255 - v for v in white))
    solid = solid.filter(ImageFilter.MinFilter(strand)).filter(ImageFilter.MaxFilter(strand))
    reach = _flood(w, h, bytes(255 - v for v in solid.tobytes()))
    core = bytes(255 if r and v else 0 for r, v in zip(reach, white))
    mask = Image.frombytes('L', (w, h), core)
    band = mask.filter(ImageFilter.MaxFilter(5))
    out = rgb.convert('RGBA')
    op, mp, bp = out.load(), mask.load(), band.load()
    for y in range(h):
        for x in range(w):
            if mp[x, y]:
                op[x, y] = (0, 0, 0, 0)
            elif bp[x, y]:
                # Colour-to-alpha against white: the edge keeps its colour, the white mixed into it goes.
                r, g, b, _ = op[x, y]
                a = max(1 - r / 255, 1 - g / 255, 1 - b / 255)
                if a < 0.05:
                    op[x, y] = (0, 0, 0, 0)
                else:
                    op[x, y] = tuple(min(255, max(0, round(255 - (255 - c) / a))) for c in (r, g, b)) + (round(a * 255),)
    return out


def trim(image: Image.Image, margin: int = 12) -> Image.Image:
    box = image.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
    left, top, right, bottom = box
    return image.crop((max(0, left - margin), max(0, top - margin),
                       min(image.width, right + margin), min(image.height, bottom + margin)))


def fit_width(image: Image.Image, width: int) -> Image.Image:
    if image.width <= width:
        return image
    return image.resize((width, round(image.height * width / image.width)), Image.Resampling.LANCZOS)


def save(image: Image.Image, name: str, quality: int = 88) -> None:
    path = ART / name
    image.save(path, 'WEBP', quality=quality, method=6)
    print(f'{path.relative_to(ROOT)}  {image.size[0]}x{image.size[1]}  {path.stat().st_size // 1024} KB')


def chibis(image: Image.Image) -> list[Image.Image]:
    """Split the sheet at the two widest fully transparent columns between the figures."""
    alpha = image.getchannel('A')
    w, h = image.size
    empty = [alpha.crop((x, 0, x + 1, h)).getbbox() is None for x in range(w)]
    runs, start = [], None
    for x, e in enumerate(empty + [False]):
        if e and start is None:
            start = x
        elif not e and start is not None:
            if start > 0 and x < w:
                runs.append((x - start, start, x))
            start = None
    cuts = sorted(sorted(runs, reverse=True)[:2], key=lambda r: r[1])
    assert len(cuts) == 2, runs
    edges = [0, (cuts[0][1] + cuts[0][2]) // 2, (cuts[1][1] + cuts[1][2]) // 2, w]
    return [trim(image.crop((edges[i], 0, edges[i + 1], h))) for i in range(3)]


def font(name: str, size: int, weight: int) -> ImageFont.FreeTypeFont:
    f = ImageFont.truetype(str(FONTS / name), size)
    try:
        f.set_variation_by_axes([weight])
    except Exception:
        pass
    return f


def banner(hero: Image.Image) -> Image.Image:
    """2:1 crop of the hero with the name on the calm left side."""
    width = hero.width
    canvas = hero.crop((0, 0, width, width // 2)).convert('RGB').resize((1600, 800), Image.Resampling.LANCZOS)
    # A soft wash behind the text so it reads on any part of the paper texture.
    wash = Image.new('L', canvas.size, 0)
    ImageDraw.Draw(wash).ellipse((-260, 80, 820, 760), fill=120)
    wash = wash.filter(ImageFilter.GaussianBlur(120))
    canvas = Image.composite(Image.new('RGB', canvas.size, (250, 243, 236)), canvas, wash)
    draw = ImageDraw.Draw(canvas)
    ink, chestnut, muted = (46, 36, 44), (140, 91, 76), (120, 104, 106)
    title = font('NotoSerifSC-VF.ttf', 190, 900)
    draw.text((120, 230), 'Shiori', font=title, fill=ink)
    _, _, right, baseline = draw.textbbox((120, 230), 'Shiori', font=title)
    draw.ellipse((right + 8, baseline - 30, right + 38, baseline), fill=chestnut)
    draw.text((126, 500), '本机运行的 AI 聊天伙伴', font=font('NotoSansSC-VF.ttf', 46, 700), fill=(79, 66, 71))
    draw.text((128, 574), '看板娘 · 佐藤栞', font=font('NotoSansSC-VF.ttf', 30, 500), fill=muted)
    draw.line((128, 640, 248, 640), fill=chestnut, width=4)
    return canvas


def main() -> None:
    ART.mkdir(parents=True, exist_ok=True)
    hero = Image.open(SRC / 'hero.webp').convert('RGB')
    save(hero, 'hero.webp', quality=86)
    save(fit_width(trim(key_white(Image.open(SRC / 'stand.webp'))), 900), 'stand.webp')
    for name in ('chat', 'memory', 'stickers', 'local'):
        save(fit_width(trim(key_white(Image.open(SRC / f'feature-{name}.webp'))), 900), f'feature-{name}.webp')
    for name, image in zip(('happy', 'annoyed', 'sleepy'), chibis(key_white(Image.open(SRC / 'chibi-set.webp')))):
        save(fit_width(image, 520), f'chibi-{name}.webp')
    banner(hero).save(OUT / 'banner.jpg', quality=88, optimize=True, progressive=True)
    print('site/assets/banner.jpg', (OUT / 'banner.jpg').stat().st_size // 1024, 'KB')
    with Image.open(ROOT / 'shiori' / 'static' / 'assets' / 'brand' / 'app-64.png') as icon:
        icon.save(OUT / 'icon.png', optimize=True)


if __name__ == '__main__':
    main()
